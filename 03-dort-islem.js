// 03 - Aritmetik İşlemler (Dört İşlem ve Modulo)

let sayi1 = 36;
let sayi2 = 6;

let toplam = sayi1 + sayi2;
let fark = sayi1 - sayi2;
let carpim = sayi1 * sayi2;
let bolum = sayi1 / sayi2;
let mod = sayi1 % sayi2;

console.log("Birinci Sayı : " + sayi1);
console.log("İkinci Sayı  : " + sayi2);
console.log("-------------------------");
console.log("Toplam       : " + toplam);
console.log("Fark         : " + fark);
console.log("Çarpım       : " + carpim);
console.log("Bölüm        : " + bolum);
console.log("Kalan (Mod)  : " + mod);
